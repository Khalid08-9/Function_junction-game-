require("dotenv").config({ quiet: true });
const fs = require("node:fs/promises");
const path = require("node:path");
const QRCode = require("qrcode");
const { SUITS, CARD_FACES } = require("../server/src/services/cardService");

function escapeHtml(text) {
    return String(text).replace(/[&<>"']/g, char => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[char]));
}

async function generate(cards, outputDir) {
    const active = cards.filter(card => CARD_FACES.has(card.card_name.toLowerCase()) && card.qr_token);
    if (active.length !== 13 || new Set(active.map(card => card.card_name.toLowerCase())).size !== 13) {
        throw new Error("Expected all 13 active standard ranks with QR tokens. Import the complete card seeds first.");
    }
    const images = path.join(outputDir, "qr-codes");
    await fs.mkdir(images, { recursive: true });
    const labels = [];
    const rankOrder = ["ace", "2", "3", "4", "5", "6", "7", "8", "9", "10", "jack", "queen", "king"];
    active.sort((a, b) => rankOrder.indexOf(a.card_name.toLowerCase()) - rankOrder.indexOf(b.card_name.toLowerCase()));
    for (const card of active) {
        const rank = card.card_name.toLowerCase();
        // Remove only the known suit-specific files generated by the old version.
        for (const suit of SUITS) {
            await fs.rm(path.join(images, `${rank}-${suit}.svg`), { force: true });
        }
        const file = `${rank}.svg`;
        const payload = card.qr_token;
        const svg = await QRCode.toString(payload, { type: "svg", errorCorrectionLevel: "M", margin: 4, width: 300 });
        await fs.writeFile(path.join(images, file), svg);
        labels.push({ name: card.card_name, payload, file });
    }
    const markdown = [
        "# Function Junction — printable physical-card QR labels", "",
        "Generated by `npm run generate:physical-qr`. These 13 QR codes identify ranks only: Ace, 2–10, Jack, Queen and King. No suits and no Joker.", "",
        "The QR payload is a card token, NOT a website link. It contains no IP address, port, session, turn or suit. Use the Scan card button inside the game website, not a separate phone's Camera app.", "",
        "## Before printing", "",
        "- Test a label with the website's Scan card button on the device where you play.",
        "- Browser camera access requires HTTPS or localhost. Allow camera permission when prompted.",
        "- No separate mobile connection or shared Wi-Fi setup is needed. The game website must still be running.",
        "- Preview this Markdown with its `qr-codes/` folder, or open `physical-card-qr-codes.html` for the print layout.",
        "- Print black-on-white at 100% scale. Each QR should be at least 30 mm square; preserve the white border.",
        "- Attach the same rank label to all real cards of that rank, regardless of suit. Print extra copies as needed.",
        "- The labels stay valid if the website's address changes, provided its card tokens stay the same.", "",
        "## Play with real cards", "",
        "1. The lecturer creates a game and chooses **Physical cards**. Students join normally.",
        "2. Shuffle the real 52-card deck, deal five real cards to each player, and keep the digital board open.",
        "3. On your turn, click Scan card in the game website and allow this device's camera.",
        "4. Hold the printed card label in front of the camera. The camera closes and the Python question appears on the SAME screen.",
        "5. Answer once, complete one move/discard on the digital board, and discard the real card.",
        "6. Every five rounds, shuffle the full real deck and deal five new real cards to each player.", "",
        "The same rank can be played on later turns, including within the same deal. Each turn permits only one card, one answer and one move/discard. A correct repeated question can earn points again on a later turn. The lecturer supervises real dealing and ownership; a rank-only QR cannot identify an individual physical card.", "",
        "Digital-card mode remains available and opens questions directly, without generating or scanning QR codes.", "",
        "## Labels", "", "| Card rank | Printable QR | Encoded token |", "| --- | --- | --- |",
        ...labels.map(label => `| ${label.name} | ![QR for ${label.name}](qr-codes/${label.file}) | \`${label.payload}\` |`), ""
    ].join("\n");
    await fs.writeFile(path.join(outputDir, "physical-card-qr-codes.md"), markdown);
    const html = `<!doctype html><html lang="en"><meta charset="utf-8"><title>Function Junction printable card labels</title>
<style>body{font:14px sans-serif;color:#000;background:#fff;margin:12mm}h1{font-size:20px}.labels{display:grid;grid-template-columns:repeat(4,42mm);gap:5mm}.label{border:1px dashed #aaa;text-align:center;padding:2mm;break-inside:avoid}.label img{width:32mm;height:32mm;display:block;margin:auto}.label strong{display:block;font-size:11px}@page{size:A4;margin:12mm}@media print{body{margin:0}.instructions{display:none}}</style>
<div class="instructions"><h1>Function Junction — 13 rank-only QR labels</h1><p>Scan using the game website's Scan card button on the same device. No phone connection or IP address is encoded. Print at 100% scale and preserve the white borders. Use the same rank label for all suits; print extra copies as needed. Camera access requires HTTPS or localhost.</p><button onclick="window.print()">Print labels</button></div><main class="labels">
${labels.map(label => `<article class="label"><img src="qr-codes/${label.file}" alt="${escapeHtml(label.name)}"><strong>${escapeHtml(label.name)}</strong></article>`).join("\n")}</main></html>`;
    await fs.writeFile(path.join(outputDir, "physical-card-qr-codes.html"), html);
    return labels;
}

async function main() {
    const pool = require("../server/src/config/database");
    try {
        const [cards] = await pool.execute("SELECT card_name, qr_token FROM cards WHERE is_active = 1 ORDER BY card_id");
        const labels = await generate(cards, path.join(__dirname, "../docs"));
        console.log(`Generated ${labels.length} rank-only QR labels (tokens, no URLs or suits)`);
        console.log("Markdown: docs/physical-card-qr-codes.md\nPrint layout: docs/physical-card-qr-codes.html");
    } finally {
        await pool.end();
    }
}

if (require.main === module) main().catch(error => {
    console.error("Could not generate physical labels:", error.message);
    process.exitCode = 1;
});

module.exports = { generate };
